// Encodes the prompts. If there is no prompt or if the encoding fails, the
// audio is ignored.
bool Cvp::Prompt::prepareBeforeFirstBlock()
{
    mTextEmbeddings.assign(mHierarchy.getPaths().size(), {});
    if(mTextEmbeddings.empty())
    {
        std::cerr << "No prompt to analyze, the prompts must be provided as the precomputed markers of the plugin input\n";
        return false;
    }
    // Each level of a hierarchical prompt is encoded with its own text, and
    // the embedding of a level is the normalized average of the embeddings of
    // its own text and of the texts of all its sublevels (a short label such as
    // "Animal" alone is not reliable, the average of several descriptions is
    // more robust). The embedding of a prompt without sublevel is its own
    // embedding. The function returns the sum of the embeddings of the node and
    // of its sublevels, or nothing if an encoding failed.
    std::function<std::vector<double>(Hierarchy::Node const&)> encode = [&](Hierarchy::Node const& node) -> std::vector<double>
    {
        auto const embedding = getEncoder()->encodeText(node.name);
        if(embedding.empty())
        {
            return {};
        }
        std::vector<double> sum(embedding.cbegin(), embedding.cend());
        for(auto const& child : node.children)
        {
            auto const childSum = encode(child);
            if(childSum.size() != sum.size())
            {
                return {};
            }
            std::transform(sum.cbegin(), sum.cend(), childSum.cbegin(), sum.begin(), std::plus<>());
        }
        std::vector<float> average(sum.cbegin(), sum.cend());
        normalize(average);
        mTextEmbeddings[node.index] = std::move(average);
        return sum;
    };
    for(auto const& root : mHierarchy.getRoots())
    {
        if(encode(root).empty())
        {
            mTextEmbeddings.clear();
            return false;
        }
    }
    return true;
}

void Cvp::Prompt::processSegment([[maybe_unused]] size_t segment, Vamp::RealTime const& timestamp, Vamp::RealTime const& duration, std::vector<float> const& embedding, FeatureSet& fs)
{
    if(embedding.empty())
    {
        return;
    }
    Feature similarity;
    similarity.hasTimestamp = true;
    similarity.timestamp = timestamp;
    similarity.hasDuration = true;
    similarity.duration = duration;
    similarity.values.reserve(mTextEmbeddings.size());
    for(auto const& textEmbedding : mTextEmbeddings)
    {
        similarity.values.push_back(static_cast<float>(dot(embedding, textEmbedding)));
    }

    // The probabilities are computed among the siblings and multiplied by the
    // probability of the parent.
    Feature probability;
    probability.hasTimestamp = true;
    probability.timestamp = timestamp;
    probability.hasDuration = true;
    probability.duration = duration;
    probability.values.assign(similarity.values.size(), 0.0f);
    auto const scale = getEncoder()->getLogitScale();
    std::function<void(std::vector<Hierarchy::Node> const&, double)> computeProbabilities = [&](std::vector<Hierarchy::Node> const& nodes, double parentProbability)
    {
        std::vector<float> scores;
        scores.reserve(nodes.size());
        for(auto const& node : nodes)
        {
            scores.push_back(similarity.values.at(node.index));
        }
        auto const probabilities = softmax(scores, scale);
        for(size_t index = 0; index < nodes.size(); ++index)
        {
            auto const nodeProbability = parentProbability * probabilities.at(index);
            probability.values.at(nodes.at(index).index) = static_cast<float>(nodeProbability);
            computeProbabilities(nodes.at(index).children, nodeProbability);
        }
    };
    computeProbabilities(mHierarchy.getRoots(), 1.0);

    auto const selected = findBest(similarity.values);
    if(selected.has_value())
    {
        Feature tag;
        tag.hasTimestamp = true;
        tag.timestamp = timestamp;
        tag.hasDuration = true;
        tag.duration = duration;
        tag.label = mHierarchy.getPaths().at(selected.value());
        tag.values.push_back(similarity.values.at(selected.value()));
        tag.values.push_back(probability.values.at(selected.value()));
        fs[1].push_back(std::move(tag));
    }
    // The outputs have at least two bins.
    similarity.values.resize(std::max(similarity.values.size(), static_cast<size_t>(2)), 0.0f);
    probability.values.resize(similarity.values.size(), 0.0f);
    fs[0].push_back(std::move(similarity));
    fs[2].push_back(std::move(probability));
}
