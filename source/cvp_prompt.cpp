Cvp::Prompt::Prompt(float inputSampleRate)
: Analyzer(inputSampleRate, 10.0f)
{
}

std::string Cvp::Prompt::getIdentifier() const
{
    return "clapprompt";
}

std::string Cvp::Prompt::getName() const
{
    return "CLAP Prompt";
}

std::string Cvp::Prompt::getDescription() const
{
    return "Zero-shot audio tagging using the CLAP and CLAP2 audio-text models of "
           "LAION. The plugin compares the embedding of each audio window with the "
           "embeddings of the text prompts provided as precomputed markers, one "
           "marker per prompt (for example generated by the tools or annotations "
           "of the host), and generates over time the similarity scores of all "
           "the prompts as well as tags carrying the most similar prompt with its "
           "score (that can be used to filter the tags in the host). The prompts "
           "can be organized hierarchically with slashes (for example, "
           "Animal/Bird/Owl): a level is represented by the average embedding of "
           "its text and of the texts of its sublevels, and the tag is the most "
           "similar prompt among all the levels (a level is selected when its "
           "sublevels do not match the audio better). The plugin also generates "
           "the probabilities of the prompts, computed with the softmax of the "
           "similarity scores among the prompts of the same level, scaled by the "
           "temperature of the model (the probability of a sublevel is the "
           "probability of its level multiplied by its probability among the "
           "sublevels). The models are trained with English "
           "captions, hence the prompts must be written in English (the audio can "
           "contain speech in any language).";
}

Cvp::Prompt::OutputList Cvp::Prompt::getOutputDescriptors() const
{
    OutputDescriptor similarity;
    similarity.identifier = "similarity";
    similarity.name = "Class Scores";
    similarity.description = "The similarity scores between the audio window and each text prompt (the levels of the hierarchical prompts are inserted before their sublevels)";
    similarity.unit = "";
    similarity.hasFixedBinCount = true;
    similarity.binNames = mHierarchy.getPaths();
    similarity.binCount = std::max(similarity.binNames.size(), static_cast<size_t>(2));
    // The similarity scores are between -1 and 1 but the similarities between
    // the audio and the texts are generally between 0 and 0.5: the extents
    // are only used to display the scores.
    similarity.hasKnownExtents = true;
    similarity.minValue = 0.0f;
    similarity.maxValue = 0.5f;
    similarity.isQuantized = false;
    similarity.sampleType = OutputDescriptor::SampleType::VariableSampleRate;
    similarity.hasDuration = true;

    OutputDescriptor tag;
    tag.identifier = "tag";
    tag.name = "Best Class";
    tag.description = "The most similar prompt of the audio window among all the levels of the hierarchical prompts, with its similarity score";
    tag.unit = "";
    tag.hasFixedBinCount = true;
    tag.binCount = 0;
    tag.hasKnownExtents = false;
    tag.minValue = 0.0f;
    tag.maxValue = 0.0f;
    tag.isQuantized = false;
    tag.sampleType = OutputDescriptor::SampleType::VariableSampleRate;
    tag.hasDuration = true;

    OutputDescriptor probability;
    probability.identifier = "probability";
    probability.name = "Class Probabilities";
    probability.description = "The probabilities of the text prompts for the audio window (the softmax of the similarity scores among the prompts of the same level, the probability of a sublevel being the probability of its level multiplied by its probability among the sublevels, hence the probabilities of the prompts of a level sum to the probability of their parent level)";
    probability.unit = "";
    probability.hasFixedBinCount = true;
    probability.binNames = similarity.binNames;
    probability.binCount = similarity.binCount;
    probability.hasKnownExtents = true;
    probability.minValue = 0.0f;
    probability.maxValue = 1.0f;
    probability.isQuantized = false;
    probability.sampleType = OutputDescriptor::SampleType::VariableSampleRate;
    probability.hasDuration = true;
    return {similarity, tag, probability};
}

