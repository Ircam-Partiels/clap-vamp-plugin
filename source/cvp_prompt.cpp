// The hosts (such as Partiels) may call this method after the initialization,
// hence the prompts are only encoded when the first block is processed.
void Cvp::Prompt::setPreComputingFeatures(FeatureSet const& fs)
{
    std::vector<std::string> labels;
    auto const it = fs.find(0);
    if(it != fs.cend())
    {
        for(auto const& feature : it->second)
        {
            labels.push_back(feature.label);
        }
    }
    mHierarchy = Hierarchy(labels);
    mTextEmbeddings.clear();
    invalidatePreparation();
}

